// What the search index holds for each file. Files outside it are still listed, parsed for symbols
// and readable from the checkout; they are just not searched (keyword or semantic).
//
//   full    — chunked into keyword search and embedded for semantic search (source, docs, config)
//   keyword — keyword search only, not embedded (tests: "how is X tested" still finds them)
//   skip    — not indexed: test snapshots, translations other than the default language, and
//             generated or data files (embedded fonts and images, SVG path data, sample data)

export type IndexLevel = 'full' | 'keyword' | 'skip';
export type SkipReason = 'snapshot' | 'translation' | 'generated' | 'data';

const SNAPSHOT = /(\.snap$|(^|\/)__snapshots__\/)/;
// A language code: `fr`, `pt-BR`, `zh_Hans`, `es-419`, or three letters with a region (`kab-KAB`).
// Bare three-letter names are left out: they are as likely to be words (`all`, `map`).
const LANG = String.raw`[a-z]{2}(?:[-_][a-z0-9]{2,4})?|[a-z]{3}[-_][a-z0-9]{2,4}`;
// Translation catalogs in a locales/i18n/l10n/translations/lang folder, laid out by language: a
// language-named file (`fr.json`) or a language folder (`fr/common.json`,
// `fr/LC_MESSAGES/messages.po`) directly under it. Other files there (`i18n/config.json`) are kept.
const TRANSLATION = new RegExp(String.raw`(?:^|/)(?:locales?|i18n|l10n|translations?|langs?)/(?:(${LANG})/(?:[^/]+/)*[^/]+|(${LANG})\.[^./]+)$`, 'i');
const DATA_FORMAT = /\.(json|ya?ml|po|properties|strings|xliff|xlf|arb|toml)$/i;
// The default language stays searchable.
const DEFAULT_LANGUAGE = /^en(?:[-_](?:us|gb))?$/i;
// Generated-file banners: an `@generated` line, a comment line with both "generated" and
// "DO NOT EDIT" (in capitals, as tools write it), or one that opens with "this file is auto-generated".
// A bare "code generated by" is not enough: hand-written comments say that too.
const GENERATED = [
  /^\s*(?:\/\/|\/?\*+|#|<!--)?\s*@generated\b/m,
  // `DO NOT EDIT` on a comment line that also says "generated" (`// Code generated by protoc. DO NOT EDIT.`),
  // not a hand-written "DO NOT EDIT the table below".
  /^\s*(?:\/\/|\/?\*+|#|<!--)[^\n]*(?:[Gg]enerated[^\n]*\bDO NOT EDIT\b|\bDO NOT EDIT\b[^\n]*[Gg]enerated)/m,
  /^\s*(?:\/\/|\/?\*+|#|<!--)\s*(?:this file (?:is|was|has been) (?:auto(?:matically)?-?)?generated|auto-?generated (?:file|code))\b/im,
];
// Below this size a file is never treated as data, whatever its content.
const DATA_MIN_BYTES = 8_000;

/** How a file is indexed, and why it is skipped. */
export function indexLevel(path: string, content: string, isTest: boolean): { level: IndexLevel; reason?: SkipReason } {
  if (SNAPSHOT.test(path)) return { level: 'skip', reason: 'snapshot' };
  const t = DATA_FORMAT.test(path) ? TRANSLATION.exec(path) : null;
  if (t && !DEFAULT_LANGUAGE.test(t[1] ?? t[2])) return { level: 'skip', reason: 'translation' };
  const head = content.slice(0, 600);
  if (GENERATED.some((re) => re.test(head))) return { level: 'skip', reason: 'generated' };
  if (isDataLike(content)) return { level: 'skip', reason: 'data' };
  return { level: isTest ? 'keyword' : 'full' };
}

/**
 * Data rather than code: most of the text sits in very long lines with almost no spaces (minified
 * code, base64 fonts, inline images; prose written one paragraph per line has a space every few
 * characters), or it is mostly digits (SVG paths, coordinates, sample drawings). Measured on a
 * large TypeScript repository, data files score 0.33–0.60 digits and ordinary code under 0.1.
 */
export function isDataLike(content: string): boolean {
  if (content.length < DATA_MIN_BYTES) return false;
  let longChars = 0;
  for (const line of content.split('\n')) {
    if (line.length <= 300) continue;
    let spaces = 0;
    for (let i = 0; i < line.length; i++) if (line.charCodeAt(i) === 32) spaces++;
    if (spaces / line.length < 0.05) longChars += line.length;
  }
  if (longChars / content.length > 0.5) return true;
  let digits = 0;
  let visible = 0;
  for (let i = 0; i < content.length; i++) {
    const c = content.charCodeAt(i);
    if (c > 32) visible++;
    if (c >= 48 && c <= 57) digits++;
  }
  return visible > 0 && digits / visible > 0.25;
}
