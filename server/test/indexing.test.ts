const FIXTURE = path.join(import.meta.dirname, 'fixtures/sample-app');
const code = 'export function add(a: number, b: number) {\n  return a + b;\n}\n';
// SVG path data, as in an icons.tsx: mostly digits.
const svgIcons = `export const icons = {\n${Array.from({ length: 80 }, (_, i) => `  i${i}: "M12.5 4.25l3.75 8.125c0.5 1.25 2.75 3.5 4.125 6.875L18.25 21.5 9.75 17.125 4.5 21.375z",`).join('\n')}\n};\n`.repeat(2);

describe('which files the search index holds', () => {
  it.each([
    ['src/app.ts', code, false, 'full'],
    ['README.md', '# Project\n', false, 'full'],
    ['packages/app/locales/en.json', '{"hello": "Hello"}', false, 'full'],
    ['locales/en-US.json', '{}', false, 'full'],
    ['public/locales/en/common.json', '{}', false, 'full'],
    ['locales/README.md', '# Translations', false, 'full'],
    ['src/app.test.ts', code, true, 'keyword'],
    // Other files in translation folders, and non-language names, stay indexed.
    ['src/i18n/config.json', '{}', false, 'full'],
    ['packages/x/lang/settings.json', '{}', false, 'full'],
    ['locales/all.json', '{}', false, 'full'],
    ['locales/base.json', '{}', false, 'full'],
    // Not language codes: `ui`, a withdrawn code (`sh`), or a version (`api-v1`).
    ['locales/ui/strings.json', '{}', false, 'full'],
    ['src/lang/sh/grammar.json', '{}', false, 'full'],
    ['locales/in/x.json', '{}', false, 'full'],
    ['lang/api-v1.json', '{}', false, 'full'],
    ['src/locales/en.json', `{${Array.from({ length: 400 }, (_, i) => `"key${i}":"Value_${i}_text"`).join(',')}}`, false, 'full'],
    // Banners only count at the start of a comment line, and long prose lines are not data.
    ['src/prompt.ts', '// Builds the prompt; the summary is code generated by the LLM later.\n' + code, false, 'full'],
    ['src/b.ts', '// Code generated by the LLM prompt builder is reviewed by hand.\n' + code, false, 'full'],
    ['src/c.ts', '/*\n * This file is auto-generated from schema.json.\n */\n' + code, false, 'skip'],
    ['src/d.ts', '/**\n * @generated by codegen\n */\n' + code, false, 'skip'],
    ['src/table.ts', '// DO NOT EDIT the table below by hand; keep in sync with the server.\n' + code, false, 'full'],
    ['AGENTS.md', '# Agents\n\nDO NOT EDIT files under dist/.\n', false, 'full'],
    ['docs/codegen.md', '# Codegen\n\nFiles we write carry an @generated marker so tools skip them.\n', false, 'full'],
    ['docs/design.md', Array.from({ length: 30 }, () => 'This paragraph explains the design in plain words, one paragraph per line as many editors write it, so the line is long but full of spaces like normal prose. '.repeat(3)).join('\n\n'), false, 'full'],
  ] as const)('%s → %s', (p, content, isTest, level) => expect(indexLevel(p, content, isTest).level).toBe(level));

  it.each([
    ['tests/__snapshots__/app.test.tsx.snap', 'exports[`x`] = `...`;', 'snapshot'],
    ['src/app.test.ts.snap', '...', 'snapshot'],
    ['packages/app/locales/ar-SA.json', '{"hello": "مرحبا"}', 'translation'],
    ['public/locales/fr/common.json', '{}', 'translation'],
    ['i18n/de.yml', 'hello: Hallo', 'translation'],
    ['locales/fr/base.json', '{}', 'translation'],
    ['locales/de/LC_MESSAGES/messages.po', 'msgid ""', 'translation'],
    ['src/locales/pt-BR.json', '{}', 'translation'],
    ['src/locales/kab-KAB.json', '{}', 'translation'],
    ['src/locales/es-419.json', '{}', 'translation'],
    ['src/locales/zh-Hant-TW.json', '{}', 'translation'],
    ['src/locales/sr_Latn_RS/app.json', '{}', 'translation'],
    ['gen/api.pb.go', '// Code generated by protoc-gen-go. DO NOT EDIT.\npackage api\n', 'generated'],
    ['src/schema.ts', '/**\n * @generated by codegen\n */\nexport type A = 1;\n', 'generated'],
    ['src/icons.tsx', svgIcons, 'data'],
    ['src/font.ts', `export const font = "${'QUJD'.repeat(5000)}";\n`, 'data'],
  ] as const)('skips %s (%s)', (p, content, reason) => expect(indexLevel(p, content, p.includes('test'))).toEqual({ level: 'skip', reason }));

  it('counts a folder as translations only with an English catalog or three languages', () => {
    // A language-tooling repo: `ts` is an ISO code (Tsonga), but js/py are not and there is no English.
    const tooling = ['src/lang/ts/grammar.json', 'src/lang/js/grammar.json', 'src/lang/py/grammar.json'];
    const app = ['src/locales/en.json', 'src/locales/fr.json', 'public/i18n/de.json', 'public/i18n/it.json', 'public/i18n/ru.json'];
    const folders = translationFolders([...tooling, ...app]);
    expect([...folders].sort()).toEqual(['public/i18n', 'src/locales']);
    expect(indexLevel('src/lang/ts/grammar.json', '{}', false, folders).level).toBe('full');
    expect(indexLevel('src/locales/fr.json', '{}', false, folders)).toEqual({ level: 'skip', reason: 'translation' });
    expect(indexLevel('public/i18n/de.json', '{}', false, folders)).toEqual({ level: 'skip', reason: 'translation' });
    expect(indexLevel('src/locales/en.json', '{}', false, folders).level).toBe('full');
  });

  it('does not mistake ordinary code for generated or data files', () => {
    expect(indexLevel('src/a.ts', '// Please do not edit this function without asking.\n' + code, false).level).toBe('full');
    const numbers = `export const config = {\n${Array.from({ length: 400 }, (_, i) => `  retries${i}: 3, // keep in sync with the server`).join('\n')}\n};\n`;
    expect(isDataLike(numbers)).toBe(false);
    expect(isDataLike(svgIcons.slice(0, 7_000))).toBe(false); // small files are never data
  });
});

describe('search index and embeddings during analysis', () => {
  /** Records the chunk texts it embeds (questions from the background review are ignored). */
  function recorder(model: string) {
    const embedded: string[] = [];
    const provider: EmbeddingProvider = {
      name: 'rec',
      model,
      dimensions: 4,
      async embed(texts) {
        for (const t of texts) if (/^[\w./-]+\n/.test(t)) embedded.push(t.slice(0, t.indexOf('\n')));
        return texts.map((t) => new Float32Array([t.length, 1, 0, 0]));
      },
    };
    return { provider, embedded };
  }

  function project() {
    const dir = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'cq-index-')), 'app');
    fs.cpSync(FIXTURE, dir, { recursive: true });
    fs.mkdirSync(path.join(dir, 'tests/__snapshots__'), { recursive: true });
    fs.writeFileSync(path.join(dir, 'tests/__snapshots__/users.test.ts.snap'), 'exports[`users`] = `<div>…</div>`;\n');
    fs.mkdirSync(path.join(dir, 'src/locales'), { recursive: true });
    fs.writeFileSync(path.join(dir, 'src/locales/en.json'), '{"greeting": "Hello"}\n');
    fs.writeFileSync(path.join(dir, 'src/locales/fr.json'), '{"greeting": "Bonjour"}\n');
    fs.writeFileSync(path.join(dir, 'src/icons.tsx'), svgIcons);
    return dir;
  }

  const run = async (db: ReturnType<typeof openDb>, dir: string, embeddings: EmbeddingProvider) => {
    let review: Promise<void> = Promise.resolve();
    await analyzeDirectory(db, new MockProvider(), embeddings, 'idx', dir, () => undefined, () => undefined, null, () => undefined, (r) => (review = r));
    await review;
  };
  const chunkPaths = (db: ReturnType<typeof openDb>) => new Set((db.prepare(`SELECT DISTINCT path FROM chunks WHERE repo_id='idx' AND searchable=1`).all() as { path: string }[]).map((r) => r.path));
  const keywordHits = (db: ReturnType<typeof openDb>, word: string) =>
    (db.prepare(`SELECT DISTINCT c.path FROM chunks_fts f JOIN chunks c ON c.id = f.rowid WHERE chunks_fts MATCH ? AND f.repo_id='idx'`).all(word) as { path: string }[]).map((r) => r.path);

  it('leaves out snapshots, other translations and data files, and does not embed tests', async () => {
    const db = openDb(':memory:');
    db.prepare(`INSERT INTO repos (id, name, url, status) VALUES ('idx', 'app', 'upload:app', 'running')`).run();
    const dir = project();
    const { provider, embedded } = recorder('m1');
    await run(db, dir, provider);

    const indexed = chunkPaths(db);
    expect(indexed.has('src/index.ts')).toBe(true);
    expect(indexed.has('src/locales/en.json')).toBe(true);
    expect(indexed.has('tests/users.test.ts')).toBe(true); // keyword search
    for (const p of ['tests/__snapshots__/users.test.ts.snap', 'src/locales/fr.json', 'src/icons.tsx']) expect(indexed.has(p)).toBe(false);
    // Still listed and stored (readable, greppable, exported), only not searchable.
    expect(db.prepare(`SELECT count(*) AS n FROM files WHERE repo_id='idx' AND path IN ('src/locales/fr.json', 'src/icons.tsx')`).get()).toEqual({ n: 2 });
    expect(db.prepare(`SELECT count(*) AS n FROM chunks WHERE repo_id='idx' AND path='src/locales/fr.json' AND searchable=0`).get()).toEqual({ n: 1 });
    expect(keywordHits(db, 'Bonjour')).toEqual([]);
    expect(keywordHits(db, 'Hello')).toEqual(['src/locales/en.json']);

    expect(embedded).toContain('src/index.ts');
    expect(embedded).not.toContain('tests/users.test.ts');
    expect(db.prepare(`SELECT count(*) AS n FROM chunks WHERE repo_id='idx' AND path='tests/users.test.ts' AND embedding IS NOT NULL`).get()).toEqual({ n: 0 });
    expect(db.prepare(`SELECT count(*) AS n FROM chunks WHERE repo_id='idx' AND embedding IS NOT NULL AND embedding_model != 'rec:m1'`).get()).toEqual({ n: 0 });
  });

  it('keeps this repository\'s CLAUDE.md (long prose lines) in search', () => {
    const claudeMd = fs.readFileSync(path.join(import.meta.dirname, '../../CLAUDE.md'), 'utf8');
    expect(indexLevel('CLAUDE.md', claudeMd, false).level).toBe('full');
  });

  it('re-analysis embeds only changed chunks, and everything again for a new embedding model', async () => {
    const db = openDb(':memory:');
    db.prepare(`INSERT INTO repos (id, name, url, status) VALUES ('idx', 'app', 'upload:app', 'running')`).run();
    const dir = project();
    const first = recorder('m1');
    await run(db, dir, first.provider);
    expect(first.embedded.length).toBeGreaterThan(3);
    const embeddedCount = () => (db.prepare(`SELECT count(*) AS n FROM chunks WHERE repo_id='idx' AND embedding IS NOT NULL`).get() as { n: number }).n;
    const total = embeddedCount();

    const unchanged = recorder('m1');
    await run(db, dir, unchanged.provider);
    expect(unchanged.embedded).toEqual([]);
    expect(embeddedCount()).toBe(total);

    fs.appendFileSync(path.join(dir, 'src/index.ts'), '\n// changed\n');
    const changed = recorder('m1');
    await run(db, dir, changed.provider);
    expect(changed.embedded).toEqual(['src/index.ts']);
    expect(embeddedCount()).toBe(total);

    // Vectors stored before the model was recorded are embedded again once, with the model recorded.
    db.prepare(`UPDATE chunks SET embedding_model=NULL WHERE repo_id='idx'`).run();
    const legacy = recorder('m1');
    await run(db, dir, legacy.provider);
    expect(legacy.embedded.length).toBe(total);
    expect(db.prepare(`SELECT count(*) AS n FROM chunks WHERE repo_id='idx' AND embedding IS NOT NULL AND embedding_model='rec:m1'`).get()).toEqual({ n: total });

    const otherModel = recorder('m2');
    await run(db, dir, otherModel.provider);
    expect(otherModel.embedded.length).toBe(total);
  });
});
