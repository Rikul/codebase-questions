// What the search index holds for each file. Files outside it are still listed, parsed for symbols
// and readable from the checkout; they are just not searched (keyword or semantic).
//
//   full    — chunked into keyword search and embedded for semantic search (source, docs, config)
//   keyword — keyword search only, not embedded (tests: "how is X tested" still finds them)
//   skip    — not indexed: test snapshots, translations other than the default language, and
//             generated or data files (embedded fonts and images, SVG path data, sample data)

export type IndexLevel = 'full' | 'keyword' | 'skip';
export type SkipReason = 'snapshot' | 'translation' | 'generated' | 'data';

const SNAPSHOT = /(\.snap$|(^|\/)__snapshots__\/)/;
// A language code: an ISO 639-1 language (`fr`), or three letters with a subtag (`kab-KAB`),
// optionally followed by a script and/or region (`pt-BR`, `es-419`, `zh_Hans`, `zh-Hant-TW`, and
// `kab-KAB` as used in the wild). Bare three-letter
// names are left out: they are as likely to be words (`all`, `map`).
const LANG = String.raw`[a-z]{2,3}(?:[-_](?:[a-z]{2,4}|\d{3})){0,2}`;
// ISO 639-1 language codes (without the withdrawn in/iw/ji/jw/mo/sh), so two-letter folders such as
// `ui` or `sh` are not languages. Some real codes are also common folder names (`ts`, `cs`, `ml`);
// translationFolders() covers those.
const ISO_639_1 = new Set(
  ('aa ab ae af ak am an ar as av ay az ba be bg bh bi bm bn bo br bs ca ce ch co cr cs cu cv cy da de dv dz ee el en eo es et eu ' +
    'fa ff fi fj fo fr fy ga gd gl gn gu gv ha he hi ho hr ht hu hy hz ia id ie ig ii ik io is it iu ja jv ka kg ki kj kk kl ' +
    'km kn ko kr ks ku kv kw ky la lb lg li ln lo lt lu lv mg mh mi mk ml mn mr ms mt my na nb nd ne ng nl nn no nr nv ny oc oj om ' +
    'or os pa pi pl ps pt qu rm rn ro ru rw sa sc sd se sg si sk sl sm sn so sq sr ss st su sv sw ta te tg th ti tk tl tn to tr ts ' +
    'tt tw ty ug uk ur uz ve vi vo wa wo xh yi yo za zh zu').split(' '),
);
/** Whether a folder or file name is a language code (see LANG). */
function isLanguage(code: string): boolean {
  const [lang, sub] = code.toLowerCase().split(/[-_]/);
  return lang.length === 2 ? ISO_639_1.has(lang) : Boolean(sub);
}
const TRANSLATION_PATH = new RegExp(String.raw`(?:^|/)(?:locales?|i18n|l10n|translations?|langs?)/(?:(${LANG})/(?:[^/]+/)*[^/]+|(${LANG})\.[^./]+)$`, 'i');
const DATA_FORMAT = /\.(json|ya?ml|po|properties|strings|xliff|xlf|arb|toml)$/i;
// The default language stays searchable: English in any script or region (`en`, `en-CA`, `en-Latn-US`).
const DEFAULT_LANGUAGE = /^en(?:[-_]|$)/i;
// Generated-file banners: an `@generated` line, a comment line with both "generated" and
// "DO NOT EDIT" (in capitals, as tools write it), or one that opens with "this file is auto-generated".
// A bare "code generated by" is not enough: hand-written comments say that too.
const GENERATED = [
  /^\s*(?:\/\/|\/?\*+|#|<!--)?\s*@generated\b/m,
  // `DO NOT EDIT` on a comment line that also says "generated" (`// Code generated by protoc. DO NOT EDIT.`),
  // not a hand-written "DO NOT EDIT the table below".
  /^\s*(?:\/\/|\/?\*+|#|<!--)[^\n]*(?:[Gg]enerated[^\n]*\bDO NOT EDIT\b|\bDO NOT EDIT\b[^\n]*[Gg]enerated)/m,
  /^\s*(?:\/\/|\/?\*+|#|<!--)\s*(?:this file (?:is|was|has been) (?:auto(?:matically)?-?)?generated|auto-?generated (?:file|code))\b/im,
];
// How much of a file's leading comments is searched for a banner (a long license header can come
// first). Only the header: code further down that mentions "generated" or `@generated` does not count.
const HEADER_MAX = 8_000;
// Below this size a file is never treated as data, whatever its content.
const DATA_MIN_BYTES = 8_000;

/** The translation folder (`src/locales`) and language of a catalog-shaped path, or null. */
function catalog(path: string): { folder: string; lang: string } | null {
  if (!DATA_FORMAT.test(path)) return null;
  const t = TRANSLATION_PATH.exec(path);
  const lang = t && (t[1] ?? t[2]);
  if (!t || !lang || !isLanguage(lang)) return null;
  const start = path[t.index] === '/' ? t.index + 1 : t.index;
  return { folder: path.slice(0, path.indexOf('/', start)), lang };
}

/**
 * Folders that really hold translations: they have an English catalog, or catalogs for at least
 * three languages. A `lang/` folder with `ts/`, `js/` and `py/` (one ISO code, no English) does not.
 */
export function translationFolders(paths: Iterable<string>): Set<string> {
  const langs = new Map<string, Set<string>>();
  for (const p of paths) {
    const c = catalog(p);
    if (c) (langs.get(c.folder) ?? langs.set(c.folder, new Set()).get(c.folder)!).add(c.lang.toLowerCase());
  }
  return new Set([...langs].filter(([, l]) => [...l].some((x) => DEFAULT_LANGUAGE.test(x)) || l.size >= 3).map(([f]) => f));
}

/**
 * How a file is indexed, and why it is skipped. `folders` (from translationFolders over the whole
 * repository) limits translations to real translation folders; without it, any catalog-shaped
 * path counts.
 */
export function indexLevel(path: string, content: string, isTest: boolean, folders?: Set<string>): { level: IndexLevel; reason?: SkipReason } {
  if (SNAPSHOT.test(path)) return { level: 'skip', reason: 'snapshot' };
  const c = catalog(path);
  if (c && (!folders || folders.has(c.folder))) {
    if (!DEFAULT_LANGUAGE.test(c.lang)) return { level: 'skip', reason: 'translation' };
    // The default-language catalog stays searchable even when minified (one long line).
    return { level: isTest ? 'keyword' : 'full' };
  }
  const head = header(content);
  if (GENERATED.some((re) => re.test(head))) return { level: 'skip', reason: 'generated' };
  if (isDataLike(content)) return { level: 'skip', reason: 'data' };
  return { level: isTest ? 'keyword' : 'full' };
}

// The file's leading comment block: blank lines, line comments (`//`, `#`, `--`, `;`) and block
// comments (C-style and HTML) before the first line of code, up to HEADER_MAX characters, and at
// least the first 600 characters (a banner can follow a `package` or `'use strict'` line).
function header(content: string): string {
  let end = 0;
  let block: string | null = null;
  for (const line of content.slice(0, HEADER_MAX).split('\n')) {
    const t = line.trim();
    if (block) {
      if (t.includes(block)) block = null;
    } else if (t.startsWith('/*') || t.startsWith('<!--')) {
      const close = t.startsWith('/*') ? '*/' : '-->';
      if (!t.slice(2).includes(close)) block = close;
    } else if (t && !/^(?:\/\/|#|--|;)/.test(t)) break;
    end += line.length + 1;
  }
  return content.slice(0, Math.max(end, 600));
}

/**
 * Data rather than code: most of the text sits in very long lines with almost no spaces (minified
 * code, base64 fonts, inline images; prose written one paragraph per line has a space every few
 * characters), or it is mostly digits (SVG paths, coordinates, sample drawings). Measured on a
 * large TypeScript repository, data files score 0.33–0.60 digits and ordinary code under 0.1.
 */
export function isDataLike(content: string): boolean {
  if (content.length < DATA_MIN_BYTES) return false;
  let longChars = 0;
  for (const line of content.split('\n')) {
    if (line.length <= 300) continue;
    let spaces = 0;
    for (let i = 0; i < line.length; i++) if (line.charCodeAt(i) === 32) spaces++;
    if (spaces / line.length < 0.05) longChars += line.length;
  }
  if (longChars / content.length > 0.5) return true;
  let digits = 0;
  let visible = 0;
  for (let i = 0; i < content.length; i++) {
    const c = content.charCodeAt(i);
    if (c > 32) visible++;
    if (c >= 48 && c <= 57) digits++;
  }
  return visible > 0 && digits / visible > 0.25;
}
