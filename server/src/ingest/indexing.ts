// What the search index holds for each file. Files outside it are still listed, parsed for symbols
// and readable from the checkout; they are just not searched (keyword or semantic).
//
//   full    — chunked into keyword search and embedded for semantic search (source, docs, config)
//   keyword — keyword search only, not embedded (tests: "how is X tested" still finds them)
//   skip    — not indexed: test snapshots, translations other than the default language, and
//             generated or data files (embedded fonts and images, SVG path data, sample data)

export type IndexLevel = 'full' | 'keyword' | 'skip';
export type SkipReason = 'snapshot' | 'translation' | 'generated' | 'data';

const SNAPSHOT = /(\.snap$|(^|\/)__snapshots__\/)/;
// Translation catalogs: a file in a locales/i18n/translations… folder, in a data format.
const TRANSLATION = /(^|\/)(locales?|i18n|l10n|translations?|langs?)\/(?:[^/]+\/)*[^/]+\.(json|ya?ml|po|properties|strings|xliff|xlf|arb|toml)$/i;
// The default-language catalog stays searchable (`en.json`, `en-US.json`, `locales/en/common.json`, …).
const DEFAULT_LOCALE = /(^|\/)(en|en[-_](us|gb)|default|base|source)(\/|\.[^/]+$)/i;
// Generated-file banners near the top: `@generated`, Go's `Code generated … DO NOT EDIT`, and the
// usual "this file is auto-generated" wording ("DO NOT EDIT" only in capitals, as tools write it).
const GENERATED = [/@generated\b/, /\bDO NOT EDIT\b/, /\b(?:this file (?:is|was|has been) (?:auto(?:matically)?-?)?generated|auto-?generated (?:file|code|by)|code generated by)\b/i];
// Below this size a file is never treated as data, whatever its content.
const DATA_MIN_BYTES = 8_000;

/** How a file is indexed, and why it is skipped. */
export function indexLevel(path: string, content: string, isTest: boolean): { level: IndexLevel; reason?: SkipReason } {
  if (SNAPSHOT.test(path)) return { level: 'skip', reason: 'snapshot' };
  const t = TRANSLATION.exec(path);
  // Only the part from the locales folder on decides the language (`en.json`, `en/common.json`).
  if (t && !DEFAULT_LOCALE.test(path.slice(t.index))) return { level: 'skip', reason: 'translation' };
  const head = content.slice(0, 600);
  if (GENERATED.some((re) => re.test(head))) return { level: 'skip', reason: 'generated' };
  if (isDataLike(content)) return { level: 'skip', reason: 'data' };
  return { level: isTest ? 'keyword' : 'full' };
}

/**
 * Data rather than code: most of the text sits in very long lines (minified code, base64 fonts,
 * inline images), or it is mostly digits (SVG paths, coordinates, sample drawings). Measured on a
 * large TypeScript repository, data files score 0.33–0.60 digits and ordinary code under 0.1.
 */
export function isDataLike(content: string): boolean {
  if (content.length < DATA_MIN_BYTES) return false;
  let longChars = 0;
  for (const line of content.split('\n')) if (line.length > 300) longChars += line.length;
  if (longChars / content.length > 0.5) return true;
  let digits = 0;
  let visible = 0;
  for (let i = 0; i < content.length; i++) {
    const c = content.charCodeAt(i);
    if (c > 32) visible++;
    if (c >= 48 && c <= 57) digits++;
  }
  return visible > 0 && digits / visible > 0.25;
}
